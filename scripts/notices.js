#!/usr/bin/env node
'use strict';
/**
 * Generates THIRD_PARTY_NOTICES.md from the installed production dependencies (name, version, license, home page).
 * Run it after changing dependencies:   npm run notices
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8'));
const rows = [];

for (const [key, meta] of Object.entries(lock.packages || {})) {
  if (!key || meta.dev || meta.devOptional) continue;                       // production only
  const pj = path.join(ROOT, key, 'package.json');
  if (!fs.existsSync(pj)) continue;
  const p = JSON.parse(fs.readFileSync(pj, 'utf8'));
  const lic = typeof p.license === 'string' ? p.license : (p.license && p.license.type) || (p.licenses && p.licenses.map(l => l.type).join(' OR ')) || 'UNKNOWN';
  const repo = (typeof p.repository === 'string' ? p.repository : p.repository && p.repository.url) || p.homepage || '';
  rows.push({ name: p.name, version: p.version, license: lic, url: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const copyleft = rows.filter(r => /GPL/i.test(r.license) && !/\bMIT\b/.test(r.license)); // "MIT OR GPL" packages are used under MIT
const md = `# Third-party notices

Garlic itself is MIT licensed (see [LICENSE](LICENSE)). It uses the open-source packages below.
This file is generated by \`npm run notices\` from the production dependencies in \`package-lock.json\`.

${copyleft.length ? `## ⚠ Copyleft components\n\n${copyleft.map(r => `- **${r.name}** ${r.version} — ${r.license}`).join('\n')}\n\n**ffmpeg** (installed through \`ffmpeg-static\`, a separate download) is licensed under the GPL when built with x264, as the bundled binary is. If you redistribute a build of Garlic that *includes* the ffmpeg binary you must comply with the GPL for that binary (provide or offer its source: https://ffmpeg.org/ and https://github.com/eugeneware/ffmpeg-static). The Garlic source code in this repository does not contain the binary.\n\n` : ''}## Packages

| Package | Version | License | Source |
|---|---|---|---|
${rows.map(r => `| ${r.name} | ${r.version} | ${r.license} | ${r.url} |`).join('\n')}

Development-only tools (Electron, ESLint, pptxgenjs, …) are not shipped inside Garlic builds. Electron is MIT licensed and bundles Chromium and Node.js under their own licenses (see \`LICENSES.chromium.html\` in an Electron distribution).
`;
fs.writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), md);
console.log(`THIRD_PARTY_NOTICES.md written (${rows.length} packages, ${copyleft.length} copyleft)`);
